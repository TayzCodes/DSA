    /**
     * Approach 1 : Uses mathematical equations and long(overflows) to solve the issue
     * Time Complexity :  O(n)
     * Space Complexity : O(1)
     * @param arr
     * @return
     */
    public static int[] repeatedNumber2(final int[] arr){
        int[] ab = new int[2];
        long n = arr.length;
        long sum = 0, actualSum = 0, sumSqr = 0, actualSumSqr = 0;

        for(int i =0;i< n;i++){
            sum+=arr[i];
            sumSqr += (long)arr[i]*(long)arr[i];
        }
        actualSum = ((n*(n+1)))/2;
        actualSumSqr = (n*(n+1)*(2*n+1))/6;
        //B-A
        long bminusa = actualSum - sum;
        //B^2-A^2
        long b2minusa2 = actualSumSqr - sumSqr;

        //Solve for the equations
        long bplusa = b2minusa2/bminusa;
        long A = (bplusa-bminusa)/2;
        long B = bplusa-A;
        //System.out.println(A+" "+B);
        ab[0] = (int)(A);
        ab[1] = (int)(B);
        return ab;

    }

    /**
     * Optimal solution 2
     * Uses XOR logic to figure out the missing and repeated numbers
     * @param arr
     * @return
     */
    public static int[] repeatedNumbersXOR(int[] arr){
        int[] ab = new int[2];
        int x=0,y=0;

        int xor1 = arr[0];
        for(int i =1;i<arr.length;i++){
            xor1 ^= arr[i];
        }
        for(int i=1;i<=arr.length;i++){
            xor1 ^= i;
        }

        int set_bit = xor1 & ~(xor1-1);
        for(int i = 0;i< arr.length;i++){
            if((arr[i] & set_bit)> 0){
                x ^= arr[i];
            }else{
                y ^= arr[i]; // repeated number
            }
        }
        for(int i = 1;i<= arr.length;i++){
            if((i & set_bit)> 0){
                x ^= i;
            }else{
                y ^= i; //repeated number
            }
        }
        ab[0] = y;
        ab[1] = x;
         return ab;

    }
